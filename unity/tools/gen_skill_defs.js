// Generates unity/Assets/SOUL/Runtime/World/SkillCatalog.cs from 기획서/스킬_슬롯_카탈로그.md section 8
// (the 80 slot parts). Run from the repo root:  node unity/tools/gen_skill_defs.js
// The catalogue is the source of truth for names, slots, grades, sources and effect text; behaviour lives in
// Game/SoulGame.Parts*.cs keyed on the ids.
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..', '..');
const md = fs.readFileSync(path.join(root, '기획서', '스킬_슬롯_카탈로그.md'), 'utf8');
const sec = md.slice(md.indexOf('## 8. 존별 파츠 표'), md.indexOf('### 8-9'));
const SLOT = { 머리: 'Head', 몸통: 'Body', 무기: 'Weapon', 팔: 'Arm', 다리: 'Legs' };
const GRADE = { 일반: 0, 정밀: 1, 희귀: 2, 고대: 3 };
const LEGACY = { counter: 'E', whirl: 'Q', wave: 'W', storm: 'R' };
const ICON = { counter: 'PARRY', whirl: 'WHIRL', wave: 'WAVE', storm: 'STORM' };
const SLOT_ICON = { Head: 'WAVE', Body: 'CORE', Weapon: 'SLASH', Arm: 'PARRY', Legs: 'DASH' };
const LINK = { corebus: 'CoreWeapon', relay: 'CoreHead', magcore: 'CoreLegs', furnace: 'CoreArm', rootnet: 'BodyAdjacent', protocore: 'CoreAll' };
const q = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\*\*/g, '') + '"';
let zone = -1; const rows = [];
for (const line of sec.split('\n')) {
  const z = line.match(/^### 8-\d\. Z(\d)/); if (z) { zone = +z[1]; continue; }
  if (!line.startsWith('| ') || line.startsWith('| id')) continue;
  const c = line.replace(/^\||\|$/g, '').split('|').map(s => s.trim());
  if (c.length < 10) continue;
  const [id, nameRaw, part, kind, grade, source, lv1, lv3, lv5a, lv5b] = c;
  const name = nameRaw.replace(/\*\*/g, '').replace(/[◆⚠]/g, '').trim();
  const slot = SLOT[part], passive = kind === 'P', cd = passive ? 0 : parseFloat(kind.replace(/[^0-9.]/g, ''));
  const link = LINK[id] ?? (nameRaw.includes('◆') ? 'Adjacent' : 'None');
  rows.push(`            new SkillDef { id = ${q(id)}, name = ${q(name)}, part = ${q(source)}, slot = Slot.${slot}, passive = ${passive}, cooldown = ${cd}, ` +
    `icon = UiArt.${ICON[id] ?? SLOT_ICON[slot]}, ${LEGACY[id] ? `legacy = KeyCode.${LEGACY[id]}, ` : ''}grade = ${GRADE[grade]}, zone = ${zone}, link = Link.${link}, costly = ${nameRaw.includes('⚠')}, ` +
    `move = ${passive ? 'null' : q(id)}, desc = ${q(lv1)}, lv3 = ${q(lv3)}, lv5a = ${q(lv5a)}, lv5b = ${q(lv5b)} },`);
}
if (rows.length !== 80) throw new Error('expected 80 rows, got ' + rows.length);
const out = `// GENERATED by unity/tools/gen_skill_defs.js from 기획서/스킬_슬롯_카탈로그.md section 8. Do not edit by hand:
// change the catalogue and re-run the generator.
using UnityEngine;

namespace Soul
{
    public static partial class Skills
    {
        static readonly SkillDef[] Catalog =
        {
${rows.join('\n')}
        };
    }
}
`;
fs.writeFileSync(path.join(root, 'unity', 'Assets', 'SOUL', 'Runtime', 'World', 'SkillCatalog.cs'), out);
console.log('wrote', rows.length, 'parts');
